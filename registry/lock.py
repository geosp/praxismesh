"""`make registry-lock`: record each template's hash in `registry/registry.lock`.

    uv run python -m registry.lock          # add new name@version entries
    uv run python -m registry.lock --check  # fail if the lock is out of date (CI)

An existing `name@version` entry is never rewritten: a changed template needs a
new version, so tasks pinned to the old one keep a stable meaning.
"""

from __future__ import annotations

import sys
from pathlib import Path

import yaml

from common.errors import RegistryError
from registry.loader import (
    LOCK_FILE,
    REGISTRY_ROOT,
    load_registry,
    read_lock,
    read_runtime_pins,
    runtime_digest,
)

HEADER = (
    "# Template hashes (sha256 of the template file and its system prompt), and the\n"
    "# pinned digest of each harness runtime (infra/dsh/requirements.txt for dsh).\n"
    "# Generated by `make registry-lock`; never edit an existing template entry.\n"
)


def update(root: Path, *, check: bool) -> list[str]:
    """Return the problems found; write the lock unless `check` is set."""
    lock = read_lock(root)
    current = {
        t.template.ref: t.hash for t in load_registry(root, check_lock=False).templates.values()
    }
    problems = [
        f"{ref}: changed under an existing version (bump `version`)"
        for ref, digest in current.items()
        if ref in lock and lock[ref] != digest
    ]
    missing = sorted(ref for ref in current if ref not in lock)
    harnesses = sorted(
        {t.template.harness for t in load_registry(root, check_lock=False).templates.values()}
        & {"dsh"}
    )
    runtimes = {h: runtime_digest(root, h) for h in harnesses}
    stale = runtimes != read_runtime_pins(root)
    if check:
        problems += [f"{ref}: not in {LOCK_FILE} (run `make registry-lock`)" for ref in missing]
        if stale:
            problems.append(
                f"runtime pins in {LOCK_FILE} are out of date (run `make registry-lock`)"
            )
    if not problems and not check and (missing or stale):
        merged = {**lock, **{ref: current[ref] for ref in missing}}
        data: dict[str, object] = {"templates": dict(sorted(merged.items()))}
        if runtimes:
            data["runtimes"] = runtimes
        (root / LOCK_FILE).write_text(HEADER + yaml.safe_dump(data, sort_keys=False))
    return problems


def main(argv: list[str]) -> int:
    try:
        problems = update(REGISTRY_ROOT, check="--check" in argv)
    except RegistryError as e:
        problems = [str(e)]
    for problem in problems:
        print(f"error: {problem}", file=sys.stderr)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
