#!/usr/bin/env -S uv run --script
# /// script
# requires-python = ">=3.11"
# dependencies = ["pyyaml>=6"]
# ///
"""Generate per-harness agent files from the canonical definitions in .agents/agents/.

    uv run .agents/sync_agents.py           # write / update / prune generated files
    uv run .agents/sync_agents.py --check   # exit 1 if generated files are stale (for CI)

Outputs:
    .claude/agents/<name>.md        Claude Code subagent
    .github/agents/<name>.agent.md  GitHub Copilot custom agent
    .codex/agents/<name>.toml       Codex CLI custom agent

Only files carrying the GENERATED marker are ever overwritten or deleted.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

import yaml

MARKER = "GENERATED by .agents/sync_agents.py"
NOTE = f"{MARKER} from .agents/agents/{{name}}.md - do not edit; edit the source and re-run the sync."
NAME_RE = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*$")
HARNESSES = ("claude", "copilot", "codex")
RESERVED = {"name", "description", *HARNESSES}


class SyncError(Exception):
    pass


def parse_source(path: Path) -> tuple[dict, str]:
    text = path.read_text(encoding="utf-8")
    m = re.match(r"^---\r?\n(.*?)\r?\n---\r?\n?(.*)$", text, re.S)
    if not m:
        raise SyncError(f"{path}: missing YAML frontmatter delimited by '---'")
    meta = yaml.safe_load(m.group(1)) or {}
    if not isinstance(meta, dict):
        raise SyncError(f"{path}: frontmatter must be a mapping")
    body = m.group(2).strip() + "\n"
    name = meta.get("name")
    if not isinstance(name, str) or not NAME_RE.match(name):
        raise SyncError(f"{path}: 'name' must be lowercase kebab-case")
    if name != path.stem:
        raise SyncError(f"{path}: name '{name}' must match file name '{path.stem}'")
    if not isinstance(meta.get("description"), str) or not meta["description"].strip():
        raise SyncError(f"{path}: 'description' is required")
    unknown = set(meta) - RESERVED
    if unknown:
        raise SyncError(
            f"{path}: unknown top-level keys {sorted(unknown)}; put harness-specific keys "
            f"under one of {list(HARNESSES)}"
        )
    for h in HARNESSES:
        block = meta.get(h)
        if block is not None and block is not False and not isinstance(block, dict):
            raise SyncError(f"{path}: '{h}' must be a mapping or false")
    if not body.strip():
        raise SyncError(f"{path}: instructions body is empty")
    return meta, body


def harness_block(meta: dict, harness: str) -> dict | None:
    block = meta.get(harness)
    if block is False:
        return None
    return dict(block or {})


def render_markdown(meta: dict, body: str, harness: str) -> str | None:
    extra = harness_block(meta, harness)
    if extra is None:
        return None
    front = {"name": meta["name"], "description": meta["description"].strip()}
    for k, v in extra.items():
        if k in ("name", "description"):
            raise SyncError(f"{meta['name']}: '{harness}.{k}' would override a shared field")
        front[k] = v
    fm = yaml.safe_dump(front, sort_keys=False, allow_unicode=True, width=1000).strip()
    note = NOTE.format(name=meta["name"])
    return f"---\n{fm}\n---\n<!-- {note} -->\n\n{body}"


def toml_value(v, where: str) -> str:
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(v)
    if isinstance(v, str):
        return json.dumps(v, ensure_ascii=False)  # JSON string escapes are valid TOML basic strings
    if isinstance(v, list):
        return "[" + ", ".join(toml_value(x, where) for x in v) + "]"
    if isinstance(v, dict):
        items = ", ".join(f"{toml_key(k)} = {toml_value(x, where)}" for k, x in v.items())
        return "{ " + items + " }" if items else "{}"
    raise SyncError(f"{where}: unsupported value type {type(v).__name__} for TOML")


def toml_key(k) -> str:
    k = str(k)
    return k if re.match(r"^[A-Za-z0-9_-]+$", k) else json.dumps(k)


def render_toml(meta: dict, body: str) -> str | None:
    extra = harness_block(meta, "codex")
    if extra is None:
        return None
    if "'''" in body:
        raise SyncError(f"{meta['name']}: body contains ''' which cannot go in a TOML literal string")
    for k in ("name", "description", "developer_instructions"):
        if k in extra:
            raise SyncError(f"{meta['name']}: 'codex.{k}' would override a generated field")
    where = f"{meta['name']}.codex"
    lines = [
        f"# {NOTE.format(name=meta['name'])}",
        f"name = {toml_value(meta['name'], where)}",
        f"description = {toml_value(meta['description'].strip(), where)}",
    ]
    lines += [f"{toml_key(k)} = {toml_value(v, where)}" for k, v in extra.items()]
    lines.append(f"developer_instructions = '''\n{body}'''")
    return "\n".join(lines) + "\n"


def desired_outputs(root: Path) -> dict[Path, str]:
    src_dir = root / ".agents" / "agents"
    out: dict[Path, str] = {}
    for src in sorted(src_dir.glob("*.md")):
        if src.name.lower() == "readme.md":
            continue
        meta, body = parse_source(src)
        name = meta["name"]
        targets = {
            root / ".claude" / "agents" / f"{name}.md": render_markdown(meta, body, "claude"),
            root / ".github" / "agents" / f"{name}.agent.md": render_markdown(meta, body, "copilot"),
            root / ".codex" / "agents" / f"{name}.toml": render_toml(meta, body),
        }
        out.update({p: c for p, c in targets.items() if c is not None})
    return out


def existing_generated(root: Path) -> set[Path]:
    found = set()
    for d, pattern in (
        (".claude/agents", "*.md"),
        (".github/agents", "*.agent.md"),
        (".codex/agents", "*.toml"),
    ):
        for p in (root / d).glob(pattern):
            try:
                head = p.read_text(encoding="utf-8")[:2000]
            except OSError:
                continue
            if MARKER in head:
                found.add(p)
    return found


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="report stale files and exit 1; write nothing")
    ap.add_argument("--root", type=Path, default=Path(__file__).resolve().parent.parent,
                    help="repository root (default: parent of .agents/)")
    args = ap.parse_args()
    root = args.root.resolve()

    try:
        want = desired_outputs(root)
    except (SyncError, yaml.YAMLError) as e:
        print(f"error: {e}", file=sys.stderr)
        return 2

    have = existing_generated(root)
    to_write = {p: c for p, c in want.items()
                if not p.exists() or p.read_text(encoding="utf-8") != c}
    to_delete = sorted(have - set(want))

    for p in want:
        if p.exists() and p not in have and p in to_write:
            print(f"error: {p.relative_to(root)} exists but was not generated; refusing to overwrite",
                  file=sys.stderr)
            return 2

    if args.check:
        for p in sorted(to_write):
            print(f"stale: {p.relative_to(root)}")
        for p in to_delete:
            print(f"orphan: {p.relative_to(root)}")
        if to_write or to_delete:
            print("run: uv run .agents/sync_agents.py", file=sys.stderr)
            return 1
        print(f"ok: {len(want)} generated agent file(s) up to date")
        return 0

    for p, c in sorted(to_write.items()):
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(c, encoding="utf-8")
        print(f"wrote: {p.relative_to(root)}")
    for p in to_delete:
        p.unlink()
        print(f"deleted: {p.relative_to(root)}")
    print(f"done: {len(want)} generated agent file(s); {len(to_write)} written, {len(to_delete)} deleted")
    return 0


if __name__ == "__main__":
    sys.exit(main())
